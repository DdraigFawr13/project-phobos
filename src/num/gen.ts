// Table generation, in float, for scripts/gen-tables.ts and the tests. Not runtime code (spec "Tables": generated once in Node and committed).

const N = 1025;
/** Entry i = round(4096 × tanh(i / 128)), i in 0 to 1024. */
export const tanhEntries = () => Array.from({ length: N }, (_, i) => Math.round(4096 * Math.tanh(i / 128)));
/** Entry i = round(4096 × exp(−i / 128)), i in 0 to 1024. */
export const expEntries = () => Array.from({ length: N }, (_, i) => Math.round(4096 * Math.exp(-i / 128)));

export function tablesSource(): string {
  const row = (a: number[]) => a.join(", ");
  return `// Generated by scripts/gen-tables.ts (npm run gen-tables); don't edit. Spec "Tables", D-006.
// TANH[i] = round(4096 × tanh(i / 128)); EXP[i] = round(4096 × exp(−i / 128)); i in 0 to 1024.
export const TANH = Int16Array.from([${row(tanhEntries())}]);
export const EXP = Int16Array.from([${row(expEntries())}]);
`;
}
